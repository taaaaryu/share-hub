function createUiTranslations(screens, panels, purposes, useCases) {
  const dictionary = { ...englishUi };
  for (const [id, name] of [...screens, ...panels]) {
    const entry = englishScreens[id];
    if (!entry) throw new Error(`Missing English screen copy: ${id}`);
    dictionary[name] = entry[0];
    dictionary[purposes[id]] = entry[1];
    dictionary[useCases[id]] = entry[2];
  }
  return dictionary;
}

function localizeMarkup(markup, locale, dictionary) {
  if (locale !== 'en') return markup;
  const replaceText = value => {
    const match = value.match(/^(\s*)([\s\S]*?)(\s*)$/);
    if (!match) return value;
    const screenChoice = match[2].match(/^(SCR-[A-Z]+-\d+) · (.*)$/);
    const translation = dictionary[match[2]] || (screenChoice ? `${screenChoice[1]} · ${dictionary[screenChoice[2]] || screenChoice[2]}` : null);
    return translation ? `${match[1]}${translation}${match[3]}` : value;
  };
  return markup
    .replace(/>([^<>]+)</g, (_, value) => `>${replaceText(value)}<`)
    .replace(/\b(aria-label|placeholder|title)="([^"]*)"/g, (_, attribute, value) => `${attribute}="${dictionary[value] || value}"`);
}
